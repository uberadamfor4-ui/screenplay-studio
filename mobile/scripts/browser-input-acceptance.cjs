const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const { chromium } = createRequire('C:/Users/User/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/placeholder.cjs')('playwright');
const out = process.env.ANDROID_QA_DIR || 'D:/ScreenplayStudio-QA/android-0.1.1';

(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 844, height: 390 }, isMobile: true, hasTouch: true });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()); });
    await page.goto('http://127.0.0.1:5205/');
    const input = page.locator('textarea').first();
    await page.locator('textarea:not([readonly])').first().waitFor();
    await page.evaluate(() => document.fonts.ready);
    await input.fill('输入法候选词……');
    await page.waitForTimeout(950);
    await input.evaluate(element => {
      element.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }));
      element.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true, data: element.value }));
    });
    await page.waitForTimeout(50);
    await page.keyboard.press('Control+z');
    assert.equal(await input.inputValue(), '', 'Unchanged composition commit added a duplicate undo entry');
    await page.keyboard.press('Control+Shift+z');
    assert.equal(await input.inputValue(), '输入法候选词……');
    const text = '胶片……中文繁體 English 日本語 한국어，长段落完整显示。'.repeat(110);
    await input.fill(text);
    await page.setViewportSize({ width: 320, height: 640 });
    await page.waitForTimeout(450);
    assert(await input.evaluate(x => x.clientHeight >= x.scrollHeight - 2), 'Portrait rotation clipped the long paragraph');
    await page.getByRole('button', { name: '下一段', exact: true }).click();
    await page.waitForTimeout(600);
    assert(await page.evaluate(() => document.activeElement?.tagName === 'TEXTAREA' && document.activeElement.value === ''), 'New paragraph lost keyboard focus');
    await page.keyboard.insertText('新增段落的中文……');
    await page.keyboard.press('Control+z');
    assert.equal(await page.locator('.paragraph.selected textarea').inputValue(), '');
    await page.keyboard.press('Control+Shift+z');
    assert.equal(await page.locator('.paragraph.selected textarea').inputValue(), '新增段落的中文……');
    await page.keyboard.press('Control+s');
    await page.waitForTimeout(1000);
    assert.equal(await page.locator('.document-title span').innerText(), '已存至本机');
    await page.getByRole('button', { name: '下一段', exact: true }).click();
    await page.getByRole('button', { name: '撤销', exact: true }).click();
    await page.waitForTimeout(1200);
    assert.deepEqual(errors, [], 'Rapid add/undo triggered a stale focus or list index error');
    await page.getByRole('button', { name: '下一段', exact: true }).click();
    await page.getByRole('button', { name: '功能', exact: true }).click();
    await page.getByRole('button', { name: '查找与替换', exact: true }).click();
    await page.getByLabel('查找文字', { exact: true }).fill('胶片');
    await page.waitForTimeout(600);
    assert.equal(await page.evaluate(() => document.activeElement?.tagName), 'INPUT', 'Pending paragraph focus stole modal input');
    await page.getByRole('button', { name: '返回写作', exact: true }).click();
    await page.waitForTimeout(1000);
    await page.reload();
    await page.locator('textarea:not([readonly])').first().waitFor();
    assert.equal(await page.locator('textarea').first().inputValue(), text);
    await page.getByRole('button', { name: '功能', exact: true }).click();
    await page.getByRole('button', { name: '导出文件', exact: true }).click();
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'SSPROJ', exact: true }).click();
    const file = await download, project = JSON.parse(await fs.readFile(await file.path(), 'utf8'));
    assert.equal(project.elements.length, 3);
    assert.equal(project.elements.filter(element => element.text === '新增段落的中文……').length, 1);
    assert.deepEqual(errors, []);
    await fs.mkdir(out, { recursive: true });
    const result = { passed: true, unchangedImeCommitDoesNotDuplicateUndo: true, landscapeToPortrait: true, longParagraph: text.length, newParagraphFocus: true, hardwareUndoRedoSave: true, rapidAddUndo: true, modalFocus: true, reloadAndExport: true };
    await fs.writeFile(path.join(out, 'input-regression.json'), JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result));
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error.stack); process.exitCode = 1; });
