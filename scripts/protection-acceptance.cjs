const { app, BrowserWindow, ipcMain } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const out = path.resolve(process.env.SCREENPLAY_GATE_OUTPUT || path.join(root, 'acceptance-results'), 'protection')
app.setPath('userData', path.join(out, 'profile-' + Date.now()))
let window, snapshot, failDisk = false, cancel = false, recoveryRead = false
const saves = [], checks = []
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
const evaluate = source => window.webContents.executeJavaScript(source)
async function until(source, name) {
  for (let i = 0; i < 100; i++) { if (await evaluate(source)) return; await wait(100) }
  throw Error('Timed out: ' + name + '; UI=' + await evaluate("JSON.stringify({status:document.querySelector('.statusbar')?.textContent,dialog:document.querySelector('[role=dialog]')?.textContent?.slice(0,500)})"))
}
async function click(title) {
  await evaluate(`document.querySelector('button[title=${JSON.stringify(title)}]').click()`)
  await wait(100)
}
async function main() {
  await fs.mkdir(out, { recursive: true }); await app.whenReady()
  ipcMain.handle('system:listFonts', () => ({ fonts: [] }))
  ipcMain.handle('system:setUiLocale', (_event, locale) => ({ locale }))
  ipcMain.handle('system:runtimeInfo', () => ({ platform: process.platform, systemVersion: '10.0.0' }))
  ipcMain.handle('revision:read', () => undefined)
  ipcMain.handle('revision:write', () => true)
  ipcMain.handle('recovery:read', () => { recoveryRead = true; return snapshot })
  ipcMain.handle('recovery:write', (_event, value) => { if (failDisk) throw Error('Injected disk failure'); snapshot = value; return true })
  const fixture = await fs.readFile(path.join(root, 'tests/fixtures/document-import/last-bus-final.ssproj'), 'utf8')
  ipcMain.handle('file:openText', () => ({ canceled: false, content: fixture, filePath: path.join(out, 'source.ssproj') }))
  ipcMain.handle('file:saveText', (_event, value) => { saves.push(value); return cancel ? { canceled: true } : { canceled: false, filePath: path.join(out, value.suggestedName) } })
  window = new BrowserWindow({ width: 1280, height: 900, show: false, webPreferences: { preload: path.join(root, 'electron/preload.cjs'), contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false } })
  await window.loadFile(path.join(root, 'dist/index.html'))
  await until("Boolean(document.querySelector('.editor-row textarea'))", 'editor')
  for (let i = 0; i < 100 && !recoveryRead; i++) await wait(50)
  assert.ok(recoveryRead, 'Startup recovery read completed before opening the fixture')
  await evaluate("new Promise(resolve=>setTimeout(resolve,200))")
  await click('打开')
  await until("Boolean(document.querySelector('.protection-file'))", 'opened file saved')
  checks.push('opened project and recovery status are distinct')
  await evaluate("document.querySelector('.editor-row textarea').focus()")
  await window.webContents.insertText('省略号……不应误报原文件已保存')
  await until("Boolean(document.querySelector('.protection-recovery'))", 'recovery saved only')
  checks.push('new text protected by recovery does not mark original saved')
  failDisk = true
  await evaluate("window.__setItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('Full','QuotaExceededError')};document.querySelector('.editor-row textarea').focus()")
  await window.webContents.insertText('两处存储失败的保密测试正文')
  await until("Boolean(document.querySelector('.protection-failed'))", 'failed storage')
  await evaluate("document.querySelector('.protection-status').click()")
  await until("Boolean(document.querySelector('.protection-dialog'))", 'protection dialog')
  await evaluate("[...document.querySelectorAll('.protection-dialog button')].find(b=>b.textContent.includes('导出问题诊断包')).click()")
  await until("document.querySelector('.protection-result').textContent.includes('已导出')", 'diagnostic exported')
  const report = saves.at(-1)
  assert.ok(!report.content.includes('保密测试正文') && !report.content.includes('source.ssproj') && !report.content.includes(root))
  assert.equal(JSON.parse(report.content).protection, 'failed')
  assert.equal(report.filePath, undefined)
  checks.push('diagnostics exclude text, names and paths; failed state remains failed')
  await evaluate("[...document.querySelectorAll('.protection-dialog button')].find(b=>b.textContent.includes('另存独立备份')).click()")
  await until("document.querySelector('.protection-result').textContent.includes('备份已保存')", 'backup')
  assert.ok(saves.at(-1).content.includes('保密测试正文'))
  assert.equal(saves.at(-1).protectFilePath, path.join(out, 'source.ssproj'))
  assert.equal(saves.at(-1).filePath, undefined)
  assert.ok(await evaluate("Boolean(document.querySelector('.statusbar span:nth-child(2)').textContent.includes('source.ssproj'))"))
  checks.push('backup exports the live draft without changing original location')
  cancel = true
  await evaluate("[...document.querySelectorAll('.protection-dialog button')].find(b=>b.textContent.includes('导出问题诊断包')).click()")
  await until("document.querySelector('.protection-result').textContent.includes('已取消')", 'canceled report')
  checks.push('cancel is not export success')
  for (const [width, height] of [[1280,900],[800,600]]) {
    window.setSize(width,height); await wait(150)
    const bounds = await evaluate("(()=>{const e=document.querySelector('.protection-dialog'),r=e.getBoundingClientRect();return {left:r.left,right:r.right,bottom:r.bottom,viewport:innerWidth,height:innerHeight,overflow:e.scrollWidth>e.clientWidth+2}})()")
    assert.ok(bounds.left>=0 && bounds.right<=bounds.viewport && bounds.bottom<=bounds.height && !bounds.overflow)
  }
  await fs.writeFile(path.join(out, 'protection.png'), (await window.webContents.capturePage()).toPNG())
  await click('关闭')
  await until("document.activeElement?.matches('.editor-row textarea')", 'writing focus restored')
  await window.webContents.insertText('关闭后继续输入')
  assert.ok(await evaluate("[...document.querySelectorAll('.editor-row textarea')].some(t=>t.value.includes('关闭后继续输入'))"))
  checks.push('closing returns to editable script')
  await fs.writeFile(path.join(out, 'results.json'), JSON.stringify({ passed: true, platform: process.platform, checks }, null, 2))
  console.log(JSON.stringify({ passed: true, platform: process.platform, checks, output: out }))
  window.destroy(); app.quit()
}
main().catch(error => { console.error(error); app.exit(1) })
